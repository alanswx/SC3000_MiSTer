#!/usr/bin/env python3
"""Generate rtl/sc3000_cart_db.vh from MAME's hash lists.

Every cartridge whose MAME slot type is not a plain ROM gets a CRC32 -> mapper
entry, so the core picks the right mapper for known dumps without the user
choosing it. Run from the repo root:
    python3 tools/gen_cart_db.py software/mame_hash/sg1000.xml software/mame_hash/sc3000_cart.xml > rtl/sc3000_cart_db.vh
"""
import sys, xml.etree.ElementTree as ET

# keep in step with sc3000_cart.sv
MAPPER = {"rom": 0, "level3": 1, "castle": 2, "othello": 3, "terebi": 4,
          "dahjee_typea": 5, "dahjee_typeb": 6, "music_editor": 7,
          "multicart": 8, "megacart": 9, "sega_315_5208": 10}

# carts the MAME lists don't have (MAME lists Loretta as SMS software)
EXTRA = [("323f357f", "sega_315_5208", "extra", "loretta",
          "Loretta no Shouzou (J), CRC from GearSF7000 / Meka"),
         ("ea7fc2d5", "level3", "extra", "esalesman",
          "Electronic Salesman (J) (Proto) (no-intro): reads RAM at 8000 from boot")]

rows = []
for path in sys.argv[1:]:
    root = ET.parse(path).getroot()
    lst = root.get("name")
    for sw in root.findall("software"):
        slot = [f.get("value") for f in sw.findall("part/feature") if f.get("name") == "slot"]
        slot = slot[0] if slot else "rom"
        if slot == "rom" or slot not in MAPPER:
            continue
        roms = sw.findall(".//dataarea[@name='rom']/rom")
        if len(roms) != 1 or not roms[0].get("crc"):
            continue
        rows.append((roms[0].get("crc").lower(), MAPPER[slot], lst, sw.get("name"), slot))

for crc, slot, lst, name, _ in EXTRA:
    rows.append((crc, MAPPER[slot], lst, name, slot))

print("// Generated by tools/gen_cart_db.py from MAME hash lists - do not edit.")
print("// CRC32 of the whole image -> {found, mapper} (sc3000_cart.sv numbering).")
print("function automatic [4:0] cart_db(input [31:0] crc);")
print("  case (crc)")
for crc, m, lst, name, slot in rows:
    print(f"    32'h{crc}: cart_db = {{1'b1, 4'd{m}}};   // {lst}:{name} ({slot})")
print("    default: cart_db = 5'd0;")
print("  endcase")
print("endfunction")
